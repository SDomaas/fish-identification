#!/usr/bin/env python3
"""
Build a YOLO object-detection training dataset from manually sorted detection_frames.

Expected input structure:
  <detection_frames>/
    fisk/                              ← fish frames  → YOLO labels generated by re-running detector
    objekter_ikke_fisk/               ← debris/objects → empty labels (negative)
    ledegjerde_uten_fisk_og_andre_objekter/  ← background → empty labels (negative)
    Rein_bakgrunn/                    ← background → empty labels (negative)

Output structure:
  <output>/
    images/train/
    images/val/
    labels/train/
    labels/val/
    dataset.yaml

Usage:
  python scripts/prepare_detector_dataset.py \
      --detection-frames /path/to/detection_frames \
      --output /path/to/detector_dataset \
      --model model.pt \
      --val-split 0.2 \
      --det-threshold 0.1
"""

import argparse
import random
import shutil
import sys
from pathlib import Path

IMAGE_EXTS = {".jpg", ".jpeg", ".png"}
FISH_CLASS = 0  # single class: fish


def load_yolo_model(model_path: str):
    try:
        from ultralytics import YOLO
    except ImportError:
        sys.exit("ultralytics not installed. Run: pip install ultralytics")
    return YOLO(model_path)


def get_images(folder: Path) -> list[Path]:
    return sorted(p for p in folder.iterdir() if p.suffix.lower() in IMAGE_EXTS)


def write_yolo_label(label_path: Path, boxes_xywhn: list):
    """Write a YOLO label file. boxes_xywhn is a list of (cx, cy, w, h) normalized."""
    with open(label_path, "w") as f:
        for cx, cy, w, h in boxes_xywhn:
            f.write(f"{FISH_CLASS} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n")


def generate_fish_labels(images: list[Path], model, threshold: float, labels_dir: Path):
    """Run YOLO on fish frames and write label files."""
    print(f"  Running detector on {len(images)} fish frames (threshold={threshold})…")
    for img_path in images:
        results = model.predict(str(img_path), conf=threshold, verbose=False)
        boxes_xywhn = []
        if results and results[0].boxes is not None:
            for box in results[0].boxes:
                xywhn = box.xywhn.cpu().numpy()[0]
                boxes_xywhn.append(xywhn.tolist())
        label_path = labels_dir / (img_path.stem + ".txt")
        write_yolo_label(label_path, boxes_xywhn)
        if not boxes_xywhn:
            print(f"    ⚠  No boxes found in {img_path.name} — empty label written")


def create_empty_labels(images: list[Path], labels_dir: Path):
    """Write empty label files for negative examples."""
    for img_path in images:
        (labels_dir / (img_path.stem + ".txt")).write_text("")


def copy_split(images: list[Path], label_src: Path,
               img_train: Path, img_val: Path,
               lbl_train: Path, lbl_val: Path,
               val_split: float, rng: random.Random):
    random.shuffle(images)
    n_val = max(1, int(len(images) * val_split)) if images else 0
    val_set = set(p.name for p in images[:n_val])
    for img_path in images:
        dst_img = (img_val if img_path.name in val_set else img_train) / img_path.name
        dst_lbl_dir = lbl_val if img_path.name in val_set else lbl_train
        shutil.copy2(img_path, dst_img)
        lbl_src = label_src / (img_path.stem + ".txt")
        if lbl_src.exists():
            shutil.copy2(lbl_src, dst_lbl_dir / lbl_src.name)
        else:
            (dst_lbl_dir / (img_path.stem + ".txt")).write_text("")
    return len(images) - n_val, n_val  # train_count, val_count


FISH_FOLDER_NAMES = {"fisk", "Fisk", "fish"}
NEG_FOLDER_DEFAULTS = [
    "objekter_ikke_fisk",
    "ledegjerde_uten_fisk_og_andre_objekter",
    "Rein_bakgrunn",
    "ikke_fisk",
    "bakgrunn",
    "sandbunn",
]


def collect_from_source(det_frames: Path, negative_folders: list,
                        fish_images: list, neg_images: list,
                        tmp_labels: Path, yolo_model, det_threshold: float):
    """Collect fish and negative images from one detection_frames source."""
    for fname in FISH_FOLDER_NAMES:
        fish_dir = det_frames / fname
        if not fish_dir.exists():
            continue
        imgs = get_images(fish_dir)
        print(f"  {det_frames.parent.name}/{fname}: {len(imgs)} fish frames")
        for img in imgs:
            lbl = fish_dir / (img.stem + ".txt")
            if lbl.exists() and lbl.stat().st_size > 0:
                shutil.copy2(lbl, tmp_labels / lbl.name)
            else:
                if yolo_model is None:
                    yolo_model = load_yolo_model("model.pt")
                generate_fish_labels([img], yolo_model, det_threshold, tmp_labels)
        fish_images.extend(imgs)

    for folder_name in negative_folders:
        neg_dir = det_frames / folder_name
        if neg_dir.exists():
            imgs = get_images(neg_dir)
            if imgs:
                create_empty_labels(imgs, tmp_labels)
                neg_images.extend(imgs)
                print(f"  {det_frames.parent.name}/{folder_name}: {len(imgs)} negative frames")

    return yolo_model


def main():
    parser = argparse.ArgumentParser(description="Prepare YOLO detector training dataset from sorted frames")
    parser.add_argument("--detection-frames", required=True, nargs="+",
                        help="One or more detection_frames folders (each containing fisk/, ikke_fisk/, etc.)")
    parser.add_argument("--output", required=True, help="Output dataset directory")
    parser.add_argument("--model", default="model.pt", help="YOLO model for re-labelling fish frames without saved labels")
    parser.add_argument("--val-split", type=float, default=0.2, help="Fraction for validation set")
    parser.add_argument("--det-threshold", type=float, default=0.1,
                        help="Detection confidence threshold when re-labelling fish frames")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--negative-folders", nargs="*", default=NEG_FOLDER_DEFAULTS,
                        help="Subfolder names to treat as negatives (empty labels)")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    out = Path(args.output)

    for d in ["images/train", "images/val", "labels/train", "labels/val"]:
        (out / d).mkdir(parents=True, exist_ok=True)

    tmp_labels = out / "_tmp_labels"
    tmp_labels.mkdir(exist_ok=True)

    fish_images: list[Path] = []
    neg_images: list[Path] = []
    yolo_model = None

    for src in args.detection_frames:
        print(f"\nSource: {src}")
        yolo_model = collect_from_source(
            Path(src), args.negative_folders,
            fish_images, neg_images,
            tmp_labels, yolo_model, args.det_threshold,
        )

    if not fish_images:
        print("⚠  No fish images found across all sources!")

    # ── Train/val split and copy ─────────────────────────────────────────────
    print("\nSplitting into train/val…")
    f_train, f_val = copy_split(
        fish_images, tmp_labels,
        out / "images/train", out / "images/val",
        out / "labels/train", out / "labels/val",
        args.val_split, rng,
    )
    n_train, n_val = copy_split(
        neg_images, tmp_labels,
        out / "images/train", out / "images/val",
        out / "labels/train", out / "labels/val",
        args.val_split, rng,
    )

    shutil.rmtree(tmp_labels)

    # ── dataset.yaml ────────────────────────────────────────────────────────
    yaml_path = out / "dataset.yaml"
    yaml_path.write_text(
        f"path: {out.resolve()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"\nnc: 1\n"
        f"names: ['fish']\n"
    )

    total_train = f_train + n_train
    total_val = f_val + n_val
    print(f"\n✅ Dataset ready: {out}")
    print(f"   Fish      — train: {f_train}  val: {f_val}")
    print(f"   Negatives — train: {n_train}  val: {n_val}")
    print(f"   Total     — train: {total_train}  val: {total_val}")
    print(f"\nTo fine-tune the detector:")
    print(f"  yolo detect train data={yaml_path} model=model.pt epochs=50 imgsz=640 batch=1")


if __name__ == "__main__":
    main()
